def norm_text(value: object) -> str:
    if value is None:
        return ""
    return " ".join(str(value).replace("\u00a0", " ").split())


def canonicalize_peredel(value: object) -> str:
    text = norm_text(value)
    return PERDEL_CANONICAL.get(text.casefold(), text)


def norm_header(value: object) -> str:
    text = norm_text(value)
    text = re.sub(r"\s*,\s*", ",", text)
    text = re.sub(r"\s*\.\s*", ".", text)
    return text


def alias_lookup() -> dict[str, str]:
    out: dict[str, str] = {}
    for canonical in ALL_COLS:
        out[norm_header(canonical).casefold()] = canonical
    for canonical, names in ALIASES.items():
        for name in names:
            out[norm_header(name).casefold()] = canonical
    return out


def canonicalize_columns(columns: Iterable[object]) -> list[str]:
    lookup = alias_lookup()
    result = []
    seen: dict[str, int] = {}
    for col in columns:
        name = lookup.get(norm_header(col).casefold(), norm_text(col))
        if name in seen:
            seen[name] += 1
            name = f"{name}__dup{seen[name]}"
        else:
            seen[name] = 0
        result.append(name)
    return result
